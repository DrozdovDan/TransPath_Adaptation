import numpy as np
import cv2
from random import choice

def generate_dcaffo(grid):
    """
    Генерирует карту размером 64x64 для задачи планирования пути.
    Клетки со значением 1 - проходимые, со значением 0 - непроходимые.
    Большинство клеток карты будут проходимыми.
    
    Returns:
        numpy.ndarray: Матрица размером 64x64 с клетками 0 и 1
    """
    # Возможные комбинации параметров (размер ядра, вероятность непроходимости)
    maze_combinations = (
        (7, 0.06),
        (7, 0.07),
        (7, 0.08),
        (7, 0.09),
        (5, 0.10),
        (5, 0.11),
        (5, 0.12),
        (5, 0.13),
        (5, 0.14),
    )
    
    # Выбираем случайную комбинацию параметров
    k, alpha = choice(maze_combinations)
    
    # Генерируем матрицу с равномерно распределёнными случайными числами от 0 до 1
    maze = np.random.rand(grid, grid)
    
    # Если значение > alpha, то клетка проходима (1), иначе непроходима (0)
    maze = np.where(maze > alpha, 1, 0)
    
    # Создаём ядро для морфологической операции открытия
    kernel = np.ones((k, k), np.uint8)
    
    # Применяем морфологическую операцию открытия для получения "блочных" препятствий
    maze = cv2.morphologyEx(maze.astype(np.uint8), cv2.MORPH_OPEN, kernel, iterations=1)
    
    return 1 - maze
